// Compile display metadata to a local module: sandboxed renderers cannot fetch JSON.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const source = new URL('../src/shared/data/monitoring.json', import.meta.url);
const destination = new URL('../src/shared/design/monitoring-labels.mjs', import.meta.url);

export async function monitoringContract(write = false) {
  const policy = JSON.parse(await readFile(source, 'utf8'));
  const constants = JSON.parse(await readFile(new URL('../src/shared/data/constants.json', import.meta.url), 'utf8'));
  if (policy.version !== 1) throw new Error('Unsupported monitoring policy version');
  const ranks = new Set();
  for (const [state, rule] of Object.entries(policy.states)) {
    if (!rule.label || !['good', 'warning', 'danger', 'neutral', 'active'].includes(rule.tone)) throw new Error(`Invalid presentation: ${state}`);
    if (rule.attentionRank !== undefined) {
      if (!Number.isInteger(rule.attentionRank) || rule.attentionRank < 1 || ranks.has(rule.attentionRank)) throw new Error(`Invalid attention rank: ${state}`);
      ranks.add(rule.attentionRank);
    }
    const seen = new Set([state]);
    let current = rule;
    while (current.transition) {
      const { state: next, after } = current.transition;
      if (!Object.hasOwn(policy.states, next) || seen.has(next) || !Number.isSafeInteger(constants[after]) || constants[after] <= 0) throw new Error(`Invalid transition: ${state}`);
      seen.add(next);
      current = policy.states[next];
    }
  }
  for (const digits of Object.values(policy.measurements.unitFractionDigits)) {
    if (!Number.isInteger(digits) || digits < 0 || digits > 6) throw new Error('Invalid measurement precision');
  }
  await sharedMessages(write, policy, constants);
  const labels = Object.fromEntries(Object.entries(policy.states).map(([state, { label, tone }]) => [state, [label, tone]]));
  const output = '// Generated by scripts/generate-monitoring.mjs from shared/data/monitoring.json.\nexport default ' + JSON.stringify(labels, null, 2) + ';\nexport const unitFractionDigits = ' + JSON.stringify(policy.measurements.unitFractionDigits) + ';\n';
  if (write) await writeFile(destination, output);
  else if (await readFile(destination, 'utf8') !== output) throw new Error('Monitoring display metadata drifted; run node scripts/generate-monitoring.mjs --write');
}
// The shared message catalog (src/shared/i18n/shared.json) becomes a module
// for sandboxed renderers and Web. Every locale must have the English keys,
// the same placeholders, and English must match the registries that still
// carry English labels for older clients. The Desktop catalog
// (src/shared/i18n/desktop.json) follows the same rules and must not redefine
// a shared key; the App reads it directly, so it generates no module.
const messagesSource = new URL('../src/shared/i18n/shared.json', import.meta.url);
const messagesDestination = new URL('../src/shared/i18n/shared-messages.mjs', import.meta.url);
const desktopSource = new URL('../src/shared/i18n/desktop.json', import.meta.url);
const placeholders = message => [...new Set((typeof message === 'string' ? [message] : Object.values(message)).flatMap(text => [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1])))].sort().join(',');

export function validateCatalog(name, catalog) {
  const english = catalog.en;
  if (!english) throw new Error(`${name} needs English messages`);
  for (const [locale, messages] of Object.entries(catalog)) {
    if (!['en', 'ko', 'ja'].includes(locale)) throw new Error(`Unsupported locale in ${name}: ${locale}`);
    const missing = Object.keys(english).filter(key => !Object.hasOwn(messages, key));
    const extra = Object.keys(messages).filter(key => !Object.hasOwn(english, key));
    if (missing.length || extra.length) throw new Error(`${name} ${locale}: missing ${missing.join(', ') || '-'}; unknown ${extra.join(', ') || '-'}`);
    for (const [key, message] of Object.entries(messages)) {
      const valid = typeof message === 'string' || (message && typeof message.other === 'string' && Object.values(message).every(text => typeof text === 'string'));
      if (!valid || placeholders(message) !== placeholders(english[key])) throw new Error(`${name} ${locale}: ${key} must keep the English placeholders`);
    }
  }
}

async function sharedMessages(write, policy, constants) {
  const catalog = JSON.parse(await readFile(messagesSource, 'utf8'));
  const desktop = JSON.parse(await readFile(desktopSource, 'utf8'));
  const { BUILTIN_METRICS } = await import('../src/shared/resource-schema.cjs');
  const states = JSON.parse(await readFile(new URL('../src/shared/data/states.json', import.meta.url), 'utf8')).states;
  validateCatalog('shared.json', catalog);
  validateCatalog('desktop.json', desktop);
  const english = catalog.en;
  const redefined = Object.keys(desktop.en).filter(key => Object.hasOwn(english, key));
  if (redefined.length) throw new Error(`desktop.json redefines shared keys: ${redefined.join(', ')}`);
  const expect = (key, value) => { if (english[key] !== value) throw new Error(`shared.json en ${key} must equal ${JSON.stringify(value)}`); };
  for (const [state, { label }] of Object.entries(policy.states)) expect(`state.${state}`, label);
  for (const [state, { text }] of Object.entries(states)) expect(`bubble.${state}`, text);
  for (const [tool, text] of Object.entries(constants.TOOL_TEXTS)) expect(`tool.${tool}`, text);
  for (const [key, { label }] of Object.entries(BUILTIN_METRICS)) expect(`metric.${key}`, label);
  const output = '// Generated by scripts/generate-monitoring.mjs from shared/i18n/shared.json.\nexport default ' + JSON.stringify(catalog, null, 2) + ';\n';
  if (write) await writeFile(messagesDestination, output);
  else if (await readFile(messagesDestination, 'utf8') !== output) throw new Error('Shared messages drifted; run node scripts/generate-monitoring.mjs --write');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await monitoringContract(process.argv.includes('--write'));
