// Compile display metadata to a local module: sandboxed renderers cannot fetch JSON.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const source = new URL('../src/shared/data/monitoring.json', import.meta.url);
const destination = new URL('../src/shared/design/monitoring-labels.mjs', import.meta.url);

export async function monitoringContract(write = false) {
  const policy = JSON.parse(await readFile(source, 'utf8'));
  const constants = JSON.parse(await readFile(new URL('../src/shared/data/constants.json', import.meta.url), 'utf8'));
  if (policy.version !== 1) throw new Error('Unsupported monitoring policy version');
  const ranks = new Set();
  for (const [state, rule] of Object.entries(policy.states)) {
    if (!rule.label || !['good', 'warning', 'danger', 'neutral', 'active'].includes(rule.tone)) throw new Error(`Invalid presentation: ${state}`);
    if (rule.attentionRank !== undefined) {
      if (!Number.isInteger(rule.attentionRank) || rule.attentionRank < 1 || ranks.has(rule.attentionRank)) throw new Error(`Invalid attention rank: ${state}`);
      ranks.add(rule.attentionRank);
    }
    const seen = new Set([state]);
    let current = rule;
    while (current.transition) {
      const { state: next, after } = current.transition;
      if (!Object.hasOwn(policy.states, next) || seen.has(next) || !Number.isSafeInteger(constants[after]) || constants[after] <= 0) throw new Error(`Invalid transition: ${state}`);
      seen.add(next);
      current = policy.states[next];
    }
  }
  for (const digits of Object.values(policy.measurements.unitFractionDigits)) {
    if (!Number.isInteger(digits) || digits < 0 || digits > 6) throw new Error('Invalid measurement precision');
  }
  const labels = Object.fromEntries(Object.entries(policy.states).map(([state, { label, tone }]) => [state, [label, tone]]));
  const output = '// Generated by scripts/generate-monitoring.mjs from shared/data/monitoring.json.\nexport default ' + JSON.stringify(labels, null, 2) + ';\nexport const unitFractionDigits = ' + JSON.stringify(policy.measurements.unitFractionDigits) + ';\n';
  if (write) await writeFile(destination, output);
  else if (await readFile(destination, 'utf8') !== output) throw new Error('Monitoring display metadata drifted; run node scripts/generate-monitoring.mjs --write');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await monitoringContract(process.argv.includes('--write'));
