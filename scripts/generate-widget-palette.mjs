// Compile the shared light/dark tokens to Swift: the macOS widget cannot read CSS.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import tokens from '../src/shared/design/tokens.cjs';
const destination = new URL('../native/macos/Shared/Palette.swift', import.meta.url);
const TOKENS = ['background', 'surface', 'foreground', 'muted', 'border', 'subtle', 'accent', 'good', 'warning', 'danger', 'info'];

export async function widgetPalette(write = false) {
  const css = tokens.readTokens();
  const lines = TOKENS.map(token => {
    const { light, dark } = tokens.colorPair(css, token);
    return `    static let ${token} = Color(light: 0x${light.slice(1)}, dark: 0x${dark.slice(1)})`;
  });
  const output = `// Generated by scripts/generate-widget-palette.mjs from src/shared/design/tokens.css.\nimport SwiftUI\n\nenum Palette {\n${lines.join('\n')}\n}\n`;
  if (write) await writeFile(destination, output);
  else if (await readFile(destination, 'utf8') !== output) throw new Error('Widget palette drifted; run node scripts/generate-widget-palette.mjs --write');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await widgetPalette(process.argv.includes('--write'));
